import { test, expect } from '@playwright/test'

test('four navigation entries have separate roles and one practice setup', async ({ page }, info) => {
  await page.goto('/')
  const nav = page.getByRole('navigation', { name: '主要導覽' })
  await expect(nav.getByRole('button')).toHaveText(['練習', '課程', '工具', '進度'])
  await expect(page.getByRole('group', { name: '練習情境' })).toHaveCount(1)
  await expect(page.getByLabel('這次練什麼')).toHaveCount(1)
  await expect(page.getByLabel('這次練什麼').locator('option')).toHaveText(['找音', '說出音名', '音程', '和弦音'])
  await expect(page.getByLabel('找音題作答方式')).toHaveCount(0)
  await expect(page.getByRole('heading', { name: '本週', exact: true })).toHaveCount(0)
  await page.screenshot({ path: info.outputPath('practice-hub.png'), fullPage: true })
  await nav.getByRole('button', { name: '課程', exact: true }).click()
  await expect(page.getByRole('heading', { name: '課程', exact: true })).toBeVisible()
  expect(await page.locator('.course-catalog').evaluate(e => (e as HTMLDetailsElement).open)).toBe(false)
  await nav.getByRole('button', { name: '工具', exact: true }).click()
  await expect(page.getByRole('tab', { name: '聽力' })).toHaveCount(0)
  await expect(page.getByRole('group', { name: '練習情境' })).toHaveCount(0)
  await expect(page.getByRole('button', { name: /開始練習|開始持琴練習/ })).toHaveCount(0)
  await expect(page.getByRole('heading', { name: '指板查詢' })).toBeVisible()
  await page.screenshot({ path: info.outputPath('reference-tools.png'), fullPage: true })
  await nav.getByRole('button', { name: '進度', exact: true }).click()
  await expect(page.getByRole('heading', { name: '本週', exact: true })).toBeVisible()
  await page.goto('/guitar')
  await expect(nav.locator('[aria-current="page"]')).toHaveText('練習')
  await expect(page.getByRole('button', { name: /彈吉他.*麥克風作答/ })).toHaveAttribute('aria-pressed', 'true')
  await expect(page.getByLabel('這次練什麼')).toHaveCount(1)
})

test('rhythm practice and tuner have one home each; closing tuner stops its input', async ({ page }) => {
  await page.goto('/')
  await page.getByRole('button', { name: /彈吉他.*麥克風作答/ }).click()
  await page.getByText('節拍與換和弦', { exact: true }).click()
  await expect(page.getByRole('button', { name: '開始一分鐘練習' })).toBeVisible()
  await expect(page.getByText('單音音高參考', { exact: true })).toHaveCount(0)
  await page.goto('/lab/fretboard')
  await expect(page.getByRole('button', { name: '開始一分鐘練習' })).toHaveCount(0)
  await page.locator('summary').filter({ hasText: /^調音$/ }).click()
  await expect(page.getByRole('button', { name: '開始收音', exact: true })).toBeVisible()
  await expect(page.getByRole('button', { name: '改用點指板', exact: true })).toHaveCount(0)
  await page.locator('summary').filter({ hasText: /^調音$/ }).click()
  await expect(page.getByRole('button', { name: '開始收音', exact: true })).toHaveCount(0)
})
